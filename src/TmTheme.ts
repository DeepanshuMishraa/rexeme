import type { Palette } from "./Palette.ts"

const escapeXml = (value: string) => value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")

/** A TextMate syntax theme named "rex", shared by every tool that reads .tmTheme files (Codex, bat, delta, yazi). */
export const render = (p: Palette): string => {
  const rules: ReadonlyArray<readonly [string, string, string, string?]> = [
    ["Comment", "comment, punctuation.definition.comment", p.muted, "italic"],
    ["String", "string, constant.other.symbol", p.green],
    ["Number", "constant.numeric, constant.language, constant.character, constant.other", p.orange],
    ["Keyword", "keyword, keyword.control, storage, storage.type, storage.modifier", p.magenta],
    ["Operator", "keyword.operator", p.cyan],
    ["Function", "entity.name.function, support.function, meta.function-call", p.blue],
    ["Type", "entity.name.type, entity.name.class, support.type, support.class", p.yellow],
    ["Tag", "entity.name.tag", p.red],
    ["Attribute", "entity.other.attribute-name", p.yellow],
    ["Variable", "variable, variable.parameter", p.fg],
    ["Punctuation", "punctuation", p.subtext],
    ["Heading", "markup.heading, entity.name.section", p.accent, "bold"],
    ["Link", "markup.underline.link", p.blue, "underline"],
    ["Inserted", "markup.inserted", p.green],
    ["Deleted", "markup.deleted", p.red],
    ["Changed", "markup.changed", p.yellow],
  ]
  const settings: ReadonlyArray<readonly [string, string]> = [
    ["background", p.bg], ["foreground", p.fg], ["caret", p.cursor],
    ["selection", p.selection], ["lineHighlight", p.surface0], ["gutterForeground", p.muted],
  ]
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by rexeme from Rex's "${escapeXml(p.name)}" theme. -->
<plist version="1.0">
<dict>
  <key>name</key><string>rex</string>
  <key>settings</key>
  <array>
    <dict>
      <key>settings</key>
      <dict>
${settings.map(([key, value]) => `        <key>${key}</key><string>${value}</string>`).join("\n")}
      </dict>
    </dict>
${rules
  .map(
    ([label, scope, color, style]) => `    <dict>
      <key>name</key><string>${label}</string>
      <key>scope</key><string>${escapeXml(scope)}</string>
      <key>settings</key>
      <dict>
        <key>foreground</key><string>${color}</string>${style ? `\n        <key>fontStyle</key><string>${style}</string>` : ""}
      </dict>
    </dict>`,
  )
  .join("\n")}
  </array>
</dict>
</plist>
`
}

export * as TmTheme from "./TmTheme.ts"
