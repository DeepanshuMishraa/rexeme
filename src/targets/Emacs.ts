import { Effect } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Shell } from "../Shell.ts"
import { Target } from "../Target.ts"

const name = "emacs"

export const render = (p: Palette): string => {
  const faces: ReadonlyArray<readonly [string, string]> = [
    ["default", `:foreground "${p.fg}" :background "${p.bg}"`],
    ["cursor", `:background "${p.cursor}"`],
    ["region", `:background "${p.selection}" :foreground "${p.selectionFg}"`],
    ["hl-line", `:background "${p.surface0}"`],
    ["fringe", `:background "${p.bg}"`],
    ["line-number", `:foreground "${p.muted}" :background "${p.bg}"`],
    ["line-number-current-line", `:foreground "${p.accent}" :background "${p.bg}" :weight bold`],
    ["vertical-border", `:foreground "${p.border}"`],
    ["mode-line", `:foreground "${p.fg}" :background "${p.surface0}" :box nil`],
    ["mode-line-inactive", `:foreground "${p.muted}" :background "${p.bgDim}" :box nil`],
    ["minibuffer-prompt", `:foreground "${p.accent}" :weight bold`],
    ["link", `:foreground "${p.blue}" :underline t`],
    ["isearch", `:foreground "${p.bg}" :background "${p.accent}"`],
    ["lazy-highlight", `:foreground "${p.bg}" :background "${p.yellow}"`],
    ["show-paren-match", `:foreground "${p.accent}" :weight bold :underline t`],
    ["error", `:foreground "${p.error}"`],
    ["warning", `:foreground "${p.warning}"`],
    ["success", `:foreground "${p.success}"`],
    ["font-lock-comment-face", `:foreground "${p.muted}" :slant italic`],
    ["font-lock-doc-face", `:foreground "${p.muted}" :slant italic`],
    ["font-lock-string-face", `:foreground "${p.green}"`],
    ["font-lock-keyword-face", `:foreground "${p.magenta}"`],
    ["font-lock-builtin-face", `:foreground "${p.cyan}"`],
    ["font-lock-function-name-face", `:foreground "${p.blue}"`],
    ["font-lock-variable-name-face", `:foreground "${p.fg}"`],
    ["font-lock-type-face", `:foreground "${p.yellow}"`],
    ["font-lock-constant-face", `:foreground "${p.orange}"`],
    ["font-lock-warning-face", `:foreground "${p.warning}"`],
  ]
  return `;;; rex-theme.el --- Generated by rexeme from Rex's "${p.name}" theme -*- lexical-binding: t -*-
(deftheme rex "Follows the Rex terminal's theme.")
(custom-theme-set-faces
 'rex
${faces.map(([face, spec]) => ` '(${face} ((t (${spec}))))`).join("\n")})
(provide-theme 'rex)
`
}

const themesDir = Effect.gen(function* () {
  const paths = yield* Paths.Service
  const xdg = join(paths.config, "emacs")
  return join((yield* Target.exists(xdg)) ? xdg : join(paths.home, ".emacs.d"), "themes")
})

export const target: Target.Target = {
  name,
  detect: Effect.gen(function* () {
    const paths = yield* Paths.Service
    return (yield* Target.exists(join(paths.home, ".emacs.d"))) || (yield* Target.exists(join(paths.config, "emacs")))
  }),
  apply: Effect.fn("Emacs.apply")(function* (palette) {
    const dir = yield* themesDir
    const path = join(dir, "rex-theme.el")
    yield* Files.writeIfChanged(path, render(palette)).pipe(Target.step(name, "write", path))
    // A running Emacs server reloads it now; exits non-zero when none is running.
    const lisp = `(progn (add-to-list 'custom-theme-load-path ${JSON.stringify(dir)}) (load-theme 'rex t))`
    const code = yield* Shell.exitCode("emacsclient", ["--eval", lisp]).pipe(Effect.orElseSucceed(() => 1))
    return code === 0 ? "reloaded in the running Emacs" : "run (load-theme 'rex t) to use it, or start an Emacs server for live reloads"
  }),
}

export * as Emacs from "./Emacs.ts"
