import { Effect } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"

const name = "gitui"

export const render = (p: Palette): string => {
  const entries: ReadonlyArray<readonly [string, string]> = [
    ["selected_tab", p.accent], ["command_fg", p.fg], ["selection_bg", p.surface1], ["selection_fg", p.fg],
    ["cmdbar_bg", p.bgDim], ["cmdbar_extra_lines_bg", p.bgDim], ["disabled_fg", p.muted],
    ["diff_line_add", p.green], ["diff_line_delete", p.red], ["diff_file_added", p.green],
    ["diff_file_removed", p.red], ["diff_file_moved", p.magenta], ["diff_file_modified", p.yellow],
    ["commit_hash", p.magenta], ["commit_time", p.cyan], ["commit_author", p.green], ["danger_fg", p.error],
    ["push_gauge_bg", p.accent], ["push_gauge_fg", p.bg], ["tag_fg", p.yellow], ["branch_fg", p.blue],
  ]
  return `// Generated by rexeme from Rex's "${p.name}" theme.\n(\n${entries.map(([key, color]) => `    ${key}: Some("${color}"),`).join("\n")}\n)\n`
}

export const target: Target.Target = {
  name,
  detect: Target.onPath("gitui"),
  apply: Effect.fn("Gitui.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const path = join(paths.config, "gitui", "theme.ron")
    yield* Files.writeIfChanged(path, render(palette)).pipe(Target.step(name, "write", path))
    return "applies next launch"
  }),
}

export * as Gitui from "./Gitui.ts"
