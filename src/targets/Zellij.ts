import { Effect, Option } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"
import { Text } from "../Text.ts"

const name = "zellij"

export const render = (p: Palette): string => `// Generated by rexeme from Rex's "${p.name}" theme.
themes {
    rex {
        fg "${p.fg}"
        bg "${p.surface1}"
        black "${p.bgDim}"
        red "${p.red}"
        green "${p.accent}"
        yellow "${p.yellow}"
        blue "${p.blue}"
        magenta "${p.magenta}"
        cyan "${p.cyan}"
        white "${p.fg}"
        orange "${p.orange}"
    }
}
`

export const target: Target.Target = {
  name,
  detect: Target.onPath("zellij"),
  apply: Effect.fn("Zellij.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const themePath = join(paths.config, "zellij", "themes", "rex.kdl")
    const configPath = join(paths.config, "zellij", "config.kdl")
    yield* Files.writeIfChanged(themePath, render(palette)).pipe(Target.step(name, "write", themePath))
    const config = Option.getOrElse(yield* Files.readOptional(configPath).pipe(Target.step(name, "read", configPath)), () => "")
    yield* Files.writeIfChanged(configPath, Text.setLine(config, /^theme\s+"[^"]*"\s*$/, `theme "rex"`)).pipe(
      Target.step(name, "write", configPath),
    )
    return "running sessions reload it live"
  }),
}

export * as Zellij from "./Zellij.ts"
