// k9s uses $XDG_CONFIG_HOME/k9s when that variable is set, else its macOS folder.
const dir = Effect.gen(function* () {
  const paths = yield* Paths.Service
  return process.env["XDG_CONFIG_HOME"] ? join(paths.config, "k9s") : join(paths.appSupport, "k9s")
})

export const target: Target.Target = {
  name,
  detect: Target.onPath("k9s"),
  apply: Effect.fn("K9s.apply")(function* (palette) {
    const base = yield* dir
    const skin = join(base, "skins", "rex.yaml")
    yield* Files.writeIfChanged(skin, render(palette)).pipe(Target.step(name, "write", skin))
    const configPath = join(base, "config.yaml")
    const config = yield* Files.readOptional(configPath).pipe(Target.step(name, "read", configPath))
    // Only a skin line that already exists is changed; k9s's nested config isn't safe to add keys to by text.
    if (Option.exists(config, (text) => /^\s+skin:\s*rex\s*$/m.test(text))) return "running k9s reloads skins live"
    if (Option.exists(config, (text) => /^\s+skin:\s*\S+\s*$/m.test(text))) {
      const updated = Text.setLine(Option.getOrElse(config, () => ""), /^(\s+)skin:\s*\S+\s*$/, "$1skin: rex")
      yield* Files.writeIfChanged(configPath, updated).pipe(Target.step(name, "write", configPath))
      return "selected the rex skin; running k9s reloads it live"
    }
    return `set k9s.ui.skin: rex in ${configPath} to use it`
  }),
}

export * as K9s from "./K9s.ts"
