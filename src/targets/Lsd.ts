import { Effect, Option } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"

const name = "lsd"
const HEADER = "# Generated by rexeme from Rex's theme. Hand-written colors.yaml files are never overwritten."

export const render = (p: Palette): string => `${HEADER}
user: '${p.yellow}'
group: '${p.cyan}'
permission:
  read: '${p.green}'
  write: '${p.yellow}'
  exec: '${p.red}'
  exec-sticky: '${p.magenta}'
  no-access: '${p.muted}'
  octal: '${p.cyan}'
  acl: '${p.cyan}'
  context: '${p.cyan}'
date:
  hour-old: '${p.green}'
  day-old: '${p.cyan}'
  older: '${p.muted}'
size:
  none: '${p.muted}'
  small: '${p.subtext}'
  medium: '${p.yellow}'
  large: '${p.orange}'
inode:
  valid: '${p.magenta}'
  invalid: '${p.muted}'
links:
  valid: '${p.magenta}'
  invalid: '${p.muted}'
tree-edge: '${p.border}'
git-status:
  default: '${p.fg}'
  unmodified: '${p.muted}'
  ignored: '${p.muted}'
  new-in-index: '${p.green}'
  new-in-workdir: '${p.green}'
  typechange: '${p.yellow}'
  deleted: '${p.red}'
  renamed: '${p.green}'
  modified: '${p.yellow}'
  conflicted: '${p.red}'
`

// colors.yaml files written by rexeme or its predecessor Hued are rexeme's to replace.
const generated = (text: string) => text.startsWith("# Generated by rexeme") || text.startsWith("# Generated by `hued")

export const target: Target.Target = {
  name,
  detect: Target.onPath("lsd"),
  apply: Effect.fn("Lsd.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const colorsPath = join(paths.config, "lsd", "colors.yaml")
    const configPath = join(paths.config, "lsd", "config.yaml")
    const existing = yield* Files.readOptional(colorsPath).pipe(Target.step(name, "read", colorsPath))
    if (Option.exists(existing, (text) => !generated(text))) {
      return `left your hand-written ${colorsPath} alone; delete it to let rexeme manage lsd's colors`
    }
    yield* Files.writeIfChanged(colorsPath, render(palette)).pipe(Target.step(name, "write", colorsPath))
    const config = Option.getOrElse(yield* Files.readOptional(configPath).pipe(Target.step(name, "read", configPath)), () => "")
    if (!/^\s*theme:\s*custom\s*$/m.test(config)) {
      if (/^color:/m.test(config)) return `set color.theme: custom in ${configPath} to use it`
      yield* Files.writeIfChanged(configPath, `${config.replace(/\n*$/, config === "" ? "" : "\n")}color:\n  theme: custom\n`).pipe(
        Target.step(name, "write", configPath),
      )
    }
    return "every new lsd run uses it"
  }),
}

export * as Lsd from "./Lsd.ts"
