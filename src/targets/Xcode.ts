const name = "xcode"
const THEME = "Rex.xccolortheme"
const DOMAIN = "com.apple.dt.Xcode"
const FONT = "SFMono-Regular - 13.0"

/** Xcode stores colors as "r g b a" with 0–1 channels. */
const rgba = (hex: Hex) => {
  const value = Number.parseInt(hex.slice(1), 16)
  const channel = (shift: number) => (((value >> shift) & 0xff) / 255).toFixed(6)
  return `${channel(16)} ${channel(8)} ${channel(0)} 1`
}

const string = (value: string) => `<string>${value}</string>`

export const render = (p: Palette): string => {
  const syntax: ReadonlyArray<readonly [string, Hex]> = [
    ["plain", p.fg], ["comment", p.muted], ["comment.doc", p.muted], ["comment.doc.keyword", p.subtext],
    ["keyword", p.magenta], ["string", p.green], ["character", p.green], ["number", p.orange], ["url", p.blue],
    ["attribute", p.yellow], ["preprocessor", p.magenta], ["mark", p.subtext], ["markup.code", p.green],
    ["declaration.type", p.yellow], ["declaration.other", p.blue],
    ["identifier.class", p.yellow], ["identifier.class.system", p.yellow],
    ["identifier.type", p.yellow], ["identifier.type.system", p.yellow],
    ["identifier.function", p.blue], ["identifier.function.system", p.blue],
    ["identifier.variable", p.fg], ["identifier.variable.system", p.cyan],
    ["identifier.constant", p.orange], ["identifier.constant.system", p.orange],
    ["identifier.macro", p.red], ["identifier.macro.system", p.red],
    ["regex", p.cyan], ["regex.capturename", p.cyan], ["regex.charname", p.cyan], ["regex.number", p.orange], ["regex.other", p.cyan],
  ]
  const dict = (entries: ReadonlyArray<readonly [string, string]>) =>
    `<dict>\n${entries.map(([key, value]) => `\t\t<key>${key}</key>\n\t\t${string(value)}`).join("\n")}\n\t</dict>`
  const top: ReadonlyArray<readonly [string, string]> = [
    ["DVTSourceTextBackground", rgba(p.bg)],
    ["DVTSourceTextCurrentLineHighlightColor", rgba(p.surface0)],
    ["DVTSourceTextInsertionPointColor", rgba(p.cursor)],
    ["DVTSourceTextInvisiblesColor", rgba(p.border)],
    ["DVTSourceTextSelectionColor", rgba(p.selection)],
    ["DVTSourceTextBlockDimBackgroundColor", rgba(p.bgDim)],
    ["DVTMarkupTextBackgroundColor", rgba(p.bgDim)],
    ["DVTMarkupTextNormalColor", rgba(p.fg)],
    ["DVTConsoleTextBackgroundColor", rgba(p.bg)],
    ["DVTConsoleTextInsertionPointColor", rgba(p.cursor)],
    ["DVTConsoleTextSelectionColor", rgba(p.selection)],
    ["DVTConsoleDebuggerInputTextColor", rgba(p.fg)],
    ["DVTConsoleDebuggerOutputTextColor", rgba(p.subtext)],
    ["DVTConsoleDebuggerPromptTextColor", rgba(p.accent)],
    ["DVTConsoleExectuableInputTextColor", rgba(p.fg)],
    ["DVTConsoleExectuableOutputTextColor", rgba(p.fg)],
  ]
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by rexeme from Rex's theme. -->
<plist version="1.0">
<dict>
${top.map(([key, value]) => `\t<key>${key}</key>\n\t${string(value)}`).join("\n")}
\t<key>DVTConsoleTextFont</key>
\t${string(FONT)}
\t<key>DVTFontAndColorVersion</key>
\t<integer>1</integer>
\t<key>DVTSourceTextSyntaxColors</key>
\t${dict(syntax.map(([key, color]) => [`xcode.syntax.${key}`, rgba(color)]))}
\t<key>DVTSourceTextSyntaxFonts</key>
\t${dict(syntax.map(([key]) => [`xcode.syntax.${key}`, FONT]))}
</dict>
</plist>
`
}

const KEYS = ["XCFontAndColorCurrentTheme", "XCFontAndColorCurrentDarkTheme"] as const

export const target: Target.Target = {
  name,
  detect: Effect.gen(function* () {
    const paths = yield* Paths.Service
    return yield* Target.exists(join(paths.home, "Library", "Developer", "Xcode"))
  }),
  apply: Effect.fn("Xcode.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const path = join(paths.home, "Library", "Developer", "Xcode", "UserData", "FontAndColorThemes", THEME)
    const changed = yield* Files.writeIfChanged(path, render(palette)).pipe(Target.step(name, "write", path))
    // Xcode picks a theme per system appearance; point both at Rex whenever the theme changes.
    if (changed) {
      for (const key of KEYS) yield* Shell.exitCode("/usr/bin/defaults", ["write", DOMAIN, key, THEME]).pipe(Effect.ignore)
    }
    return "applies the next time Xcode opens"
  }),
}

