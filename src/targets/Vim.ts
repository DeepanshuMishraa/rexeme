import { Effect, Option } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"
import { Neovim } from "./Neovim.ts"

const name = "vim"

const ATTRIBUTES = ["bold", "italic", "underline", "undercurl", "strikethrough"] as const

/** Neovim's highlight table as a Vim colorscheme; tree-sitter and LSP groups don't exist in Vim. */
export const render = (p: Palette): string => {
  const lines = Neovim.highlights(p)
    .filter(([group]) => /^[A-Za-z]+$/.test(group))
    .map(([group, style]) => {
      if (style.link) return `hi! link ${group} ${style.link}`
      const attributes = ATTRIBUTES.filter((attribute) => style[attribute] === true)
      const fields = [
        style.fg ? `guifg=${style.fg}` : "guifg=NONE",
        style.bg ? `guibg=${style.bg}` : "guibg=NONE",
        style.sp ? `guisp=${style.sp}` : undefined,
        `gui=${attributes.length > 0 ? attributes.join(",") : "NONE"}`,
        `cterm=${attributes.filter((a) => a !== "undercurl").join(",") || "NONE"}`,
      ].filter((field) => field !== undefined)
      return `hi ${group} ${fields.join(" ")}`
    })
  return [
    `" Generated by rexeme from Rex's "${p.name}" theme. Changes are overwritten on the next sync.`,
    "hi clear",
    `if exists("syntax_on") | syntax reset | endif`,
    "set termguicolors",
    `set background=${p.appearance}`,
    `let g:colors_name = "rex"`,
    `let g:terminal_ansi_colors = [${p.ansi.map((color) => `"${color}"`).join(", ")}]`,
    ...lines,
  ].join("\n") + "\n"
}

export const target: Target.Target = {
  name,
  detect: Effect.gen(function* () {
    const paths = yield* Paths.Service
    return (yield* Target.exists(join(paths.home, ".vimrc"))) || (yield* Target.exists(join(paths.home, ".vim")))
  }),
  apply: Effect.fn("Vim.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const path = join(paths.home, ".vim", "colors", "rex.vim")
    yield* Files.writeIfChanged(path, render(palette)).pipe(Target.step(name, "write", path))
    const vimrc = join(paths.home, ".vimrc")
    const config = yield* Files.readOptional(vimrc).pipe(Target.step(name, "read", vimrc))
    return Option.exists(config, (text) => /^\s*colorscheme\s+rex\b/m.test(text))
      ? "new Vim sessions use it (:colorscheme rex in open ones)"
      : "add `colorscheme rex` to ~/.vimrc to use it"
  }),
}

export * as Vim from "./Vim.ts"
