import { Effect } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"
import { Text } from "../Text.ts"

const name = "alacritty"
const NAMES = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"] as const

export const render = (p: Palette): string => {
  const group = (offset: number) => NAMES.map((color, index) => `${color} = "${p.ansi[offset + index] ?? p.fg}"`).join("\n")
  return `# Generated by rexeme from Rex's "${p.name}" theme.
[colors.primary]
background = "${p.bg}"
foreground = "${p.fg}"

[colors.cursor]
cursor = "${p.cursor}"
text = "${p.cursorText}"

[colors.selection]
background = "${p.selection}"
text = "${p.selectionFg}"

[colors.normal]
${group(0)}

[colors.bright]
${group(8)}
`
}

export const target: Target.Target = {
  name,
  detect: Effect.gen(function* () {
    const paths = yield* Paths.Service
    return yield* Target.exists(join(paths.config, "alacritty", "alacritty.toml"))
  }),
  apply: Effect.fn("Alacritty.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const themePath = join(paths.config, "alacritty", "rex.toml")
    const configPath = join(paths.config, "alacritty", "alacritty.toml")
    yield* Files.writeIfChanged(themePath, render(palette)).pipe(Target.step(name, "write", themePath))
    const config = yield* Files.read(configPath).pipe(Target.step(name, "read", configPath))
    if (config.includes(themePath) || config.includes("alacritty/rex.toml")) return "reloads live"
    // An existing import list is the user's; editing TOML arrays in place isn't safe.
    if (/^\s*import\s*=/m.test(config)) return `add "${themePath}" to general.import in ${configPath}`
    yield* Files.writeIfChanged(configPath, Text.setTomlValue(config, "general", "import", JSON.stringify([themePath]))).pipe(
      Target.step(name, "write", configPath),
    )
    return "imported rex.toml; reloads live"
  }),
}

export * as Alacritty from "./Alacritty.ts"
