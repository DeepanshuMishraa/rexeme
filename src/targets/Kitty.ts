import { Effect } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"
import { Text } from "../Text.ts"

const name = "kitty"
const THEME_FILE = "rex-theme.conf"

export const render = (p: Palette): string =>
  [
    `# Generated by rexeme from Rex's "${p.name}" theme.`,
    `background ${p.bg}`,
    `foreground ${p.fg}`,
    `cursor ${p.cursor}`,
    `cursor_text_color ${p.cursorText}`,
    `selection_background ${p.selection}`,
    `selection_foreground ${p.selectionFg}`,
    `url_color ${p.blue}`,
    `active_border_color ${p.accent}`,
    `inactive_border_color ${p.border}`,
    `active_tab_background ${p.bg}`,
    `active_tab_foreground ${p.fg}`,
    `inactive_tab_background ${p.bgDim}`,
    `inactive_tab_foreground ${p.muted}`,
    `tab_bar_background ${p.bgDim}`,
    ...p.ansi.map((color, index) => `color${index} ${color}`),
  ].join("\n") + "\n"

export const target: Target.Target = {
  name,
  detect: Effect.gen(function* () {
    const paths = yield* Paths.Service
    return yield* Target.exists(join(paths.config, "kitty", "kitty.conf"))
  }),
  apply: Effect.fn("Kitty.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const themePath = join(paths.config, "kitty", THEME_FILE)
    const configPath = join(paths.config, "kitty", "kitty.conf")
    yield* Files.writeIfChanged(themePath, render(palette)).pipe(Target.step(name, "write", themePath))
    const config = yield* Files.read(configPath).pipe(Target.step(name, "read", configPath))
    // Last in the file, so the theme wins over earlier color lines.
    yield* Files.writeIfChanged(configPath, Text.setLine(config, /^include\s+rex-theme\.conf\s*$/, `include ${THEME_FILE}`)).pipe(
      Target.step(name, "write", configPath),
    )
    // SIGUSR1 makes kitty reload kitty.conf.
    return (yield* Target.reload("kitty", "USR1")) ? "reloaded running kitty" : "applies next launch"
  }),
}

export * as Kitty from "./Kitty.ts"
