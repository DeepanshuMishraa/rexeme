import { Effect, Option } from "effect"
import { join } from "node:path"
import type { Hex } from "../Color.ts"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Shell } from "../Shell.ts"
import { Target } from "../Target.ts"
import { Text } from "../Text.ts"

const name = "spotify"
const THEME = "Rex"

const bare = (hex: Hex) => hex.slice(1)

/** A Spicetify color scheme for Spotify. */
export const render = (p: Palette): string => {
  const colors: ReadonlyArray<readonly [string, Hex]> = [
    ["text", p.fg], ["subtext", p.subtext], ["main", p.bg], ["main-elevated", p.surface0], ["highlight", p.surface1],
    ["highlight-elevated", p.surface1], ["sidebar", p.bgDim], ["player", p.bgDim], ["card", p.surface0], ["shadow", p.bgDim],
    ["selected-row", p.fg], ["button", p.accent], ["button-active", p.accent], ["button-disabled", p.muted],
    ["tab-active", p.surface1], ["notification", p.blue], ["notification-error", p.error], ["misc", p.border],
  ]
  return `; Generated by rexeme from Rex's "${p.name}" theme.\n[rex]\n${colors.map(([key, color]) => `${key} = ${bare(color)}`).join("\n")}\n`
}

export const target: Target.Target = {
  name,
  detect: Effect.gen(function* () {
    const paths = yield* Paths.Service
    return yield* Target.exists(join(paths.config, "spicetify", "config-xpui.ini"))
  }),
  apply: Effect.fn("Spicetify.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const dir = join(paths.config, "spicetify")
    const scheme = join(dir, "Themes", THEME, "color.ini")
    yield* Files.writeIfChanged(scheme, render(palette)).pipe(Target.step(name, "write", scheme))
    const userCss = join(dir, "Themes", THEME, "user.css")
    if (!(yield* Target.exists(userCss))) yield* Files.writeIfChanged(userCss, "/* Colors come from color.ini, written by rexeme. */\n").pipe(Target.step(name, "write", userCss))
    const configPath = join(dir, "config-xpui.ini")
    const config = yield* Files.readOptional(configPath).pipe(Target.step(name, "read", configPath))
    const selected = Option.exists(config, (text) => /^current_theme\s*=\s*Rex\s*$/m.test(text) && /^color_scheme\s*=\s*rex\s*$/m.test(text))
    if (!selected) {
      const text = Option.getOrElse(config, () => "")
      const updated = Text.setKeyValue(Text.setKeyValue(text, "current_theme", THEME), "color_scheme", "rex")
      yield* Files.writeIfChanged(configPath, updated).pipe(Target.step(name, "write", configPath))
      return "selected the Rex theme; run `spicetify apply` once to patch Spotify"
    }
    // Pushes the new colors into the already-patched Spotify.
    const code = yield* Shell.exitCode("spicetify", ["refresh"]).pipe(Effect.orElseSucceed(() => 1))
    return code === 0 ? "refreshed Spotify's theme; Spotify shows it after a reload" : "run `spicetify refresh` to push the new colors"
  }),
}

export * as Spicetify from "./Spicetify.ts"
