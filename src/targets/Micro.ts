import { Effect } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"

const name = "micro"

export const render = (p: Palette): string => {
  const links: ReadonlyArray<readonly [string, string]> = [
    ["default", `${p.fg},${p.bg}`], ["comment", p.muted], ["identifier", p.blue], ["constant", p.orange],
    ["constant.string", p.green], ["constant.number", p.orange], ["statement", p.magenta], ["symbol", p.cyan],
    ["preproc", p.magenta], ["type", p.yellow], ["special", p.red], ["underlined", p.blue], ["error", p.error],
    ["todo", p.yellow], ["diff-added", p.green], ["diff-modified", p.yellow], ["diff-deleted", p.red],
    ["gutter-error", p.error], ["gutter-warning", p.warning], ["statusline", `${p.fg},${p.surface0}`],
    ["tabbar", `${p.muted},${p.bgDim}`], ["indent-char", p.border], ["line-number", `${p.muted},${p.bg}`],
    ["current-line-number", `${p.accent},${p.bg}`], ["cursor-line", p.surface0], ["color-column", p.surface0],
    ["selection", `${p.selectionFg},${p.selection}`], ["divider", p.border], ["message", p.fg],
  ]
  return [`# Generated by rexeme from Rex's "${p.name}" theme.`, ...links.map(([group, value]) => `color-link ${group} "${value}"`)].join("\n") + "\n"
}

export const target: Target.Target = {
  name,
  detect: Target.onPath("micro"),
  apply: Effect.fn("Micro.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const dir = process.env["MICRO_CONFIG_HOME"] ?? join(paths.config, "micro")
    const scheme = join(dir, "colorschemes", "rex.micro")
    yield* Files.writeIfChanged(scheme, render(palette)).pipe(Target.step(name, "write", scheme))
    yield* Target.updateJson(name, join(dir, "settings.json"), (settings) => ({ ...settings, colorscheme: "rex" }))
    return "applies next launch (set MICRO_TRUECOLOR=1 for exact colors)"
  }),
}

export * as Micro from "./Micro.ts"
