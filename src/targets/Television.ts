import { Effect, Option } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"
import { Text } from "../Text.ts"

const name = "television"

export const render = (p: Palette): string => `# Generated by rexeme from Rex's "${p.name}" theme.
background = "${p.bg}"
border_fg = "${p.border}"
text_fg = "${p.fg}"
dimmed_text_fg = "${p.muted}"
input_text_fg = "${p.accent}"
result_count_fg = "${p.accent}"
result_name_fg = "${p.blue}"
result_line_number_fg = "${p.yellow}"
result_value_fg = "${p.fg}"
selection_bg = "${p.surface1}"
selection_fg = "${p.fg}"
match_fg = "${p.accent}"
preview_title_fg = "${p.orange}"
channel_mode_fg = "${p.magenta}"
remote_control_mode_fg = "${p.green}"
send_to_channel_mode_fg = "${p.cyan}"
`

export const target: Target.Target = {
  name,
  detect: Target.onPath("tv"),
  apply: Effect.fn("Television.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const dir = join(paths.config, "television")
    const themePath = join(dir, "themes", "rex.toml")
    const configPath = join(dir, "config.toml")
    yield* Files.writeIfChanged(themePath, render(palette)).pipe(Target.step(name, "write", themePath))
    const config = Option.getOrElse(yield* Files.readOptional(configPath).pipe(Target.step(name, "read", configPath)), () => "")
    yield* Files.writeIfChanged(configPath, Text.setTomlValue(config, "ui", "theme", '"rex"')).pipe(Target.step(name, "write", configPath))
    return "the next tv run uses it"
  }),
}

export * as Television from "./Television.ts"
