const toml = (style: Style) => {
  const fields = [
    style.fg ? `fg = "${style.fg}"` : undefined,
    style.bg ? `bg = "${style.bg}"` : undefined,
    style.modifiers ? `modifiers = [${style.modifiers.map((m) => `"${m}"`).join(", ")}]` : undefined,
    style.underline ? `underline = { color = "${style.underline.color}", style = "${style.underline.style}" }` : undefined,
  ].filter((field) => field !== undefined)
  return `{ ${fields.join(", ")} }`
}

export const render = (p: Palette.Palette): string =>
  [`# Generated by rexeme from Rex's "${p.name}" theme.`, ...scopes(p).map(([scope, style]) => `"${scope}" = ${toml(style)}`)].join("\n") + "\n"

export const target: Target.Target = {
  name,
  detect: Effect.gen(function* () {
    const paths = yield* Paths.Service
    return (yield* Target.onPath("hx")) || (yield* Target.exists(join(paths.config, "helix")))
  }),
  apply: Effect.fn("Helix.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const themePath = join(paths.config, "helix", "themes", "rex.toml")
    const configPath = join(paths.config, "helix", "config.toml")
    yield* Files.writeIfChanged(themePath, render(palette)).pipe(Target.step(name, "write", themePath))
    const config = Option.getOrElse(yield* Files.readOptional(configPath).pipe(Target.step(name, "read", configPath)), () => "")
    yield* Files.writeIfChanged(configPath, Text.setTomlTopLevel(config, "theme", '"rex"')).pipe(Target.step(name, "write", configPath))
    // SIGUSR1 makes Helix reload its config and theme.
    return (yield* Target.reload("hx", "USR1")) ? "reloaded running Helix" : "applies next launch"
  }),
}

