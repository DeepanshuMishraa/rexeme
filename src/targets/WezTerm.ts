import { Effect, Option } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"

const name = "wezterm"

export const render = (p: Palette): string => `# Generated by rexeme from Rex's "${p.name}" theme.
[colors]
background = "${p.bg}"
foreground = "${p.fg}"
cursor_bg = "${p.cursor}"
cursor_fg = "${p.cursorText}"
cursor_border = "${p.cursor}"
selection_bg = "${p.selection}"
selection_fg = "${p.selectionFg}"
split = "${p.border}"
ansi = [${p.ansi.slice(0, 8).map((color) => `"${color}"`).join(", ")}]
brights = [${p.ansi.slice(8).map((color) => `"${color}"`).join(", ")}]

[metadata]
name = "rex"
`

const configPaths = Effect.gen(function* () {
  const paths = yield* Paths.Service
  return [join(paths.home, ".wezterm.lua"), join(paths.config, "wezterm", "wezterm.lua")]
})

export const target: Target.Target = {
  name,
  detect: Effect.gen(function* () {
    for (const path of yield* configPaths) if (yield* Target.exists(path)) return true
    return false
  }),
  apply: Effect.fn("WezTerm.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const themePath = join(paths.config, "wezterm", "colors", "rex.toml")
    yield* Files.writeIfChanged(themePath, render(palette)).pipe(Target.step(name, "write", themePath))
    // The config is Lua; rexeme doesn't rewrite code, so selecting it is up to the user.
    for (const path of yield* configPaths) {
      const config = yield* Files.readOptional(path).pipe(Target.step(name, "read", path))
      if (Option.exists(config, (text) => /color_scheme\s*=\s*["']rex["']/.test(text))) return "applies on WezTerm's next config reload"
    }
    return `set config.color_scheme = "rex" in your wezterm.lua to use it`
  }),
}

export * as WezTerm from "./WezTerm.ts"
