import { Effect, Option } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Shell } from "../Shell.ts"
import { Target } from "../Target.ts"
import { Text } from "../Text.ts"

const name = "tmux"

export const render = (p: Palette): string => `# Generated by rexeme from Rex's "${p.name}" theme.
set -g status-style "fg=${p.subtext},bg=${p.bgDim}"
set -g status-left-style "fg=${p.bg},bg=${p.accent},bold"
set -g status-right-style "fg=${p.subtext},bg=${p.bgDim}"
set -g window-status-style "fg=${p.muted},bg=${p.bgDim}"
set -g window-status-current-style "fg=${p.fg},bg=${p.surface1},bold"
set -g window-status-activity-style "fg=${p.yellow},bg=${p.bgDim}"
set -g pane-border-style "fg=${p.border}"
set -g pane-active-border-style "fg=${p.accent}"
set -g message-style "fg=${p.fg},bg=${p.surface0}"
set -g message-command-style "fg=${p.fg},bg=${p.surface0}"
set -g mode-style "fg=${p.selectionFg},bg=${p.selection}"
set -g display-panes-active-colour "${p.accent}"
set -g display-panes-colour "${p.muted}"
set -g clock-mode-colour "${p.accent}"
`

const configPath = Effect.fn("Tmux.configPath")(function* () {
  const paths = yield* Paths.Service
  const classic = join(paths.home, ".tmux.conf")
  return (yield* Target.exists(classic)) ? classic : join(paths.config, "tmux", "tmux.conf")
})

export const target: Target.Target = {
  name,
  detect: Target.onPath("tmux"),
  apply: Effect.fn("Tmux.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const themePath = join(paths.config, "tmux", "rex.conf")
    yield* Files.writeIfChanged(themePath, render(palette)).pipe(Target.step(name, "write", themePath))
    const path = yield* configPath()
    const config = Option.getOrElse(yield* Files.readOptional(path).pipe(Target.step(name, "read", path)), () => "")
    const line = `source-file -q ${JSON.stringify(themePath)}`
    yield* Files.writeIfChanged(path, Text.setLine(config, /^source-file -q ".*\/tmux\/rex\.conf"\s*$/, line)).pipe(
      Target.step(name, "write", path),
    )
    // Applies to a running server straight away; exits non-zero when none is running.
    const code = yield* Shell.exitCode("tmux", ["source-file", themePath]).pipe(Effect.orElseSucceed(() => 1))
    return code === 0 ? "applied to the running tmux server" : "applies when tmux starts"
  }),
}

export * as Tmux from "./Tmux.ts"
