import { Effect, Option } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"
import { Text } from "../Text.ts"

const name = "rio"
const NAMES = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"] as const

export const render = (p: Palette): string => `# Generated by rexeme from Rex's "${p.name}" theme.
[colors]
background = "${p.bg}"
foreground = "${p.fg}"
cursor = "${p.cursor}"
vi-cursor = "${p.accent}"
selection-background = "${p.selection}"
selection-foreground = "${p.selectionFg}"
tabs = "${p.bgDim}"
tabs-active = "${p.accent}"
split = "${p.border}"
${NAMES.map((color, index) => `${color} = "${p.ansi[index] ?? p.fg}"`).join("\n")}
${NAMES.map((color, index) => `light-${color} = "${p.ansi[index + 8] ?? p.fg}"`).join("\n")}
`

export const target: Target.Target = {
  name,
  detect: Effect.gen(function* () {
    const paths = yield* Paths.Service
    return (yield* Target.onPath("rio")) || (yield* Target.exists(join(paths.config, "rio")))
  }),
  apply: Effect.fn("Rio.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const themePath = join(paths.config, "rio", "themes", "rex.toml")
    const configPath = join(paths.config, "rio", "config.toml")
    yield* Files.writeIfChanged(themePath, render(palette)).pipe(Target.step(name, "write", themePath))
    const config = Option.getOrElse(yield* Files.readOptional(configPath).pipe(Target.step(name, "read", configPath)), () => "")
    yield* Files.writeIfChanged(configPath, Text.setTomlTopLevel(config, "theme", '"rex"')).pipe(Target.step(name, "write", configPath))
    return "running Rio reloads it live"
  }),
}

export * as Rio from "./Rio.ts"
