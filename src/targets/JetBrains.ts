import { Effect, Option } from "effect"
import { readdirSync } from "node:fs"
import { join } from "node:path"
import type { Hex } from "../Color.ts"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"
import { Text } from "../Text.ts"

const name = "jetbrains"
const SCHEME = "Rex"

const bare = (hex: Hex) => hex.slice(1)

const ANSI = ["BLACK", "RED", "GREEN", "YELLOW", "BLUE", "MAGENTA", "CYAN", "GRAY"] as const
const BRIGHT = ["DARKGRAY", "RED_BRIGHT", "GREEN_BRIGHT", "YELLOW_BRIGHT", "BLUE_BRIGHT", "MAGENTA_BRIGHT", "CYAN_BRIGHT", "WHITE"] as const

/** An editor color scheme (.icls) on top of Darcula or the light default, shared by every JetBrains IDE. */
export const render = (p: Palette): string => {
  const colors: ReadonlyArray<readonly [string, Hex]> = [
    ["CARET_COLOR", p.cursor], ["CARET_ROW_COLOR", p.surface0], ["SELECTION_BACKGROUND", p.selection],
    ["SELECTION_FOREGROUND", p.selectionFg], ["GUTTER_BACKGROUND", p.bg], ["LINE_NUMBERS_COLOR", p.muted],
    ["LINE_NUMBER_ON_CARET_ROW_COLOR", p.accent], ["INDENT_GUIDE", p.border], ["SELECTED_INDENT_GUIDE", p.borderStrong],
    ["RIGHT_MARGIN_COLOR", p.border], ["WHITESPACES", p.border], ["TEARLINE_COLOR", p.border],
    ["CONSOLE_BACKGROUND_KEY", p.bg], ["DOCUMENTATION_COLOR", p.surface0], ["LOOKUP_COLOR", p.surface0],
    ["ADDED_LINES_COLOR", p.green], ["MODIFIED_LINES_COLOR", p.yellow], ["DELETED_LINES_COLOR", p.red],
  ]
  const text: ReadonlyArray<readonly [string, Hex, number?]> = [
    ["DEFAULT_KEYWORD", p.magenta], ["DEFAULT_STRING", p.green], ["DEFAULT_NUMBER", p.orange],
    ["DEFAULT_LINE_COMMENT", p.muted, 2], ["DEFAULT_BLOCK_COMMENT", p.muted, 2], ["DEFAULT_DOC_COMMENT", p.muted, 2],
    ["DEFAULT_FUNCTION_DECLARATION", p.blue], ["DEFAULT_FUNCTION_CALL", p.blue], ["DEFAULT_CLASS_NAME", p.yellow],
    ["DEFAULT_INTERFACE_NAME", p.yellow], ["DEFAULT_CONSTANT", p.orange], ["DEFAULT_OPERATION_SIGN", p.cyan],
    ["DEFAULT_IDENTIFIER", p.fg], ["DEFAULT_LOCAL_VARIABLE", p.fg], ["DEFAULT_PARAMETER", p.fg],
    ["DEFAULT_INSTANCE_FIELD", p.fg], ["DEFAULT_STATIC_FIELD", p.orange], ["DEFAULT_METADATA", p.yellow],
    ["DEFAULT_TAG", p.red], ["DEFAULT_ATTRIBUTE", p.yellow], ["DEFAULT_BRACES", p.subtext], ["DEFAULT_BRACKETS", p.subtext],
    ["DEFAULT_PARENTHS", p.subtext], ["DEFAULT_COMMA", p.subtext], ["DEFAULT_DOT", p.subtext], ["DEFAULT_SEMICOLON", p.subtext],
    ["DEFAULT_VALID_STRING_ESCAPE", p.cyan], ["CONSOLE_NORMAL_OUTPUT", p.fg], ["CONSOLE_ERROR_OUTPUT", p.error],
    ["CONSOLE_SYSTEM_OUTPUT", p.subtext], ["CONSOLE_USER_INPUT", p.green],
    ...ANSI.map((color, index): readonly [string, Hex] => [`CONSOLE_${color}_OUTPUT`, p.ansi[index] ?? p.fg]),
    ...BRIGHT.map((color, index): readonly [string, Hex] => [`CONSOLE_${color}_OUTPUT`, p.ansi[index + 8] ?? p.fg]),
  ]
  const attribute = ([key, color, fontType]: readonly [string, Hex, number?]) =>
    `    <option name="${key}">\n      <value>\n        <option name="FOREGROUND" value="${bare(color)}" />${fontType ? `\n        <option name="FONT_TYPE" value="${fontType}" />` : ""}\n      </value>\n    </option>`
  return `<!-- Generated by rexeme from Rex's "${p.name}" theme. -->
<scheme name="${SCHEME}" version="142" parent_scheme="${p.appearance === "dark" ? "Darcula" : "Default"}">
  <colors>
${colors.map(([key, color]) => `    <option name="${key}" value="${bare(color)}" />`).join("\n")}
  </colors>
  <attributes>
    <option name="TEXT">
      <value>
        <option name="FOREGROUND" value="${bare(p.fg)}" />
        <option name="BACKGROUND" value="${bare(p.bg)}" />
      </value>
    </option>
${text.map(attribute).join("\n")}
  </attributes>
</scheme>
`
}

const GLOBAL_SCHEME = `<application>
  <component name="EditorColorsManagerImpl">
    <global_color_scheme name="${SCHEME}" />
  </component>
</application>
`

const PRODUCT = /^(IntelliJIdea|IdeaIC|WebStorm|PyCharm|PyCharmCE|GoLand|CLion|Rider|RustRover|DataGrip|PhpStorm|RubyMine|Aqua|DataSpell|AndroidStudio)\d/

/** Every JetBrains IDE configuration folder, including Android Studio's. */
const configDirs = Effect.gen(function* () {
  const paths = yield* Paths.Service
  const roots = [join(paths.appSupport, "JetBrains"), join(paths.appSupport, "Google")]
  return roots.flatMap((root) => {
    try {
      return readdirSync(root)
        .filter((entry) => PRODUCT.test(entry))
        .map((entry) => join(root, entry))
    } catch {
      return []
    }
  })
})

export const target: Target.Target = {
  name,
  detect: Effect.map(configDirs, (dirs) => dirs.length > 0),
  apply: Effect.fn("JetBrains.apply")(function* (palette) {
    const dirs = yield* configDirs
    const scheme = render(palette)
    for (const dir of dirs) {
      const path = join(dir, "colors", `${SCHEME}.icls`)
      yield* Files.writeIfChanged(path, scheme).pipe(Target.step(name, "write", path))
      const options = join(dir, "options", "colors.scheme.xml")
      const current = yield* Files.readOptional(options).pipe(Target.step(name, "read", options))
      const updated = Option.match(current, {
        onNone: () => GLOBAL_SCHEME,
        onSome: (text) =>
          /<global_color_scheme name="[^"]*"\s*\/>/.test(text)
            ? Text.setLine(text, /^(\s*)<global_color_scheme name="[^"]*"\s*\/>\s*$/, `$1<global_color_scheme name="${SCHEME}" />`)
            : text,
      })
      yield* Files.writeIfChanged(options, updated).pipe(Target.step(name, "write", options))
    }
    return `${dirs.length} IDE${dirs.length === 1 ? "" : "s"}; applies the next time each opens`
  }),
}

export * as JetBrains from "./JetBrains.ts"
