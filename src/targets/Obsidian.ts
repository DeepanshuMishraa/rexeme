const Vaults = Schema.Struct({ vaults: Schema.Record(Schema.String, Schema.Struct({ path: Schema.String })) })

const vaults = Effect.gen(function* () {
  const paths = yield* Paths.Service
  const registry = join(paths.appSupport, "obsidian", "obsidian.json")
  const text = yield* Files.readOptional(registry).pipe(Target.step(name, "read", registry))
  return Option.match(text, {
    onNone: () => [],
    onSome: (raw) =>
      Option.match(Schema.decodeUnknownOption(Schema.fromJsonString(Vaults))(raw), {
        onNone: () => [],
        onSome: (decoded) => Object.values(decoded.vaults).map((vault) => vault.path),
      }),
  })
})

export const target: Target.Target = {
  name,
  detect: Effect.gen(function* () {
    const paths = yield* Paths.Service
    return yield* Target.exists(join(paths.appSupport, "obsidian", "obsidian.json"))
  }),
  apply: Effect.fn("Obsidian.apply")(function* (palette) {
    const found = yield* Effect.filter(yield* vaults, (vault) => Target.exists(join(vault, ".obsidian")))
    for (const vault of found) {
      const snippet = join(vault, ".obsidian", "snippets", `${SNIPPET}.css`)
      yield* Files.writeIfChanged(snippet, render(palette)).pipe(Target.step(name, "write", snippet))
      yield* Target.updateJson(name, join(vault, ".obsidian", "appearance.json"), (settings) => {
        // rexeme's predecessor, Hued, enabled its own "hued" snippet; two theme snippets would fight.
        const enabled = (Array.isArray(settings["enabledCssSnippets"]) ? settings["enabledCssSnippets"] : []).filter(
          (snippet) => snippet !== LEGACY_SNIPPET,
        )
        return {
          ...settings,
          // Obsidian's own light/dark base, so anything the snippet doesn't cover matches too.
          theme: palette.appearance === "dark" ? "obsidian" : "moonstone",
          enabledCssSnippets: enabled.includes(SNIPPET) ? enabled : [...enabled, SNIPPET],
        }
      })
    }
    return found.length > 0 ? `${found.length} vault${found.length === 1 ? "" : "s"}; open vaults update live` : "no vaults found"
  }),
}

export * as Obsidian from "./Obsidian.ts"
