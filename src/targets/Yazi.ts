import { Effect, Option } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"
import { Text } from "../Text.ts"
import { TmTheme } from "../TmTheme.ts"

const name = "yazi"

/** A yazi flavor: UI colors in flavor.toml, code previews from the shared tmTheme. */
export const render = (p: Palette): string => `# Generated by rexeme from Rex's "${p.name}" theme.
[mgr]
cwd = { fg = "${p.accent}" }
hovered = { fg = "${p.fg}", bg = "${p.surface1}", bold = true }
preview_hovered = { underline = true }
find_keyword = { fg = "${p.yellow}", bold = true }
find_position = { fg = "${p.magenta}", bg = "reset", bold = true }
marker_copied = { fg = "${p.green}", bg = "${p.green}" }
marker_cut = { fg = "${p.red}", bg = "${p.red}" }
marker_marked = { fg = "${p.cyan}", bg = "${p.cyan}" }
marker_selected = { fg = "${p.accent}", bg = "${p.accent}" }
count_copied = { fg = "${p.bg}", bg = "${p.green}" }
count_cut = { fg = "${p.bg}", bg = "${p.red}" }
count_selected = { fg = "${p.bg}", bg = "${p.accent}" }
border_symbol = "│"
border_style = { fg = "${p.border}" }
syntect_theme = "./tmtheme.xml"

[tabs]
active = { fg = "${p.bg}", bg = "${p.accent}", bold = true }
inactive = { fg = "${p.muted}", bg = "${p.surface0}" }

[mode]
normal_main = { fg = "${p.bg}", bg = "${p.accent}", bold = true }
normal_alt = { fg = "${p.accent}", bg = "${p.surface0}" }
select_main = { fg = "${p.bg}", bg = "${p.magenta}", bold = true }
select_alt = { fg = "${p.magenta}", bg = "${p.surface0}" }
unset_main = { fg = "${p.bg}", bg = "${p.red}", bold = true }
unset_alt = { fg = "${p.red}", bg = "${p.surface0}" }

[status]
perm_type = { fg = "${p.blue}" }
perm_read = { fg = "${p.yellow}" }
perm_write = { fg = "${p.red}" }
perm_exec = { fg = "${p.green}" }
perm_sep = { fg = "${p.muted}" }
progress_label = { fg = "${p.fg}", bold = true }
progress_normal = { fg = "${p.accent}", bg = "${p.surface0}" }
progress_error = { fg = "${p.error}", bg = "${p.surface0}" }

[input]
border = { fg = "${p.accent}" }
title = {}
value = {}
selected = { reversed = true }

[cmp]
border = { fg = "${p.accent}" }

[tasks]
border = { fg = "${p.accent}" }
title = {}
hovered = { fg = "${p.fg}", bg = "${p.surface1}" }

[which]
mask = { bg = "${p.bgDim}" }
cand = { fg = "${p.cyan}" }
rest = { fg = "${p.muted}" }
desc = { fg = "${p.fg}" }
separator_style = { fg = "${p.muted}" }

[help]
on = { fg = "${p.cyan}" }
run = { fg = "${p.magenta}" }
hovered = { bg = "${p.surface1}", bold = true }
footer = { fg = "${p.fg}", bg = "${p.surface0}" }

[notify]
title_info = { fg = "${p.info}" }
title_warn = { fg = "${p.warning}" }
title_error = { fg = "${p.error}" }

[filetype]
rules = [
  { mime = "image/*", fg = "${p.yellow}" },
  { mime = "{audio,video}/*", fg = "${p.magenta}" },
  { mime = "application/{zip,rar,7z*,tar,gzip,xz,zstd,bzip*,lzma,compress,archive,cpio,arj,xar,ms-cab*}", fg = "${p.red}" },
  { mime = "application/{pdf,doc,rtf}", fg = "${p.cyan}" },
  { name = "*", is = "orphan", fg = "${p.error}" },
  { name = "*", is = "exec", fg = "${p.green}" },
  { name = "*/", fg = "${p.blue}" },
]
`

export const target: Target.Target = {
  name,
  detect: Target.onPath("yazi"),
  apply: Effect.fn("Yazi.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const dir = join(paths.config, "yazi")
    const flavor = join(dir, "flavors", "rex.yazi")
    yield* Files.writeIfChanged(join(flavor, "flavor.toml"), render(palette)).pipe(Target.step(name, "write", flavor))
    yield* Files.writeIfChanged(join(flavor, "tmtheme.xml"), TmTheme.render(palette)).pipe(Target.step(name, "write", flavor))
    const themePath = join(dir, "theme.toml")
    const theme = Option.getOrElse(yield* Files.readOptional(themePath).pipe(Target.step(name, "read", themePath)), () => "")
    const updated = Text.setTomlValue(Text.setTomlValue(theme, "flavor", "dark", '"rex"'), "flavor", "light", '"rex"')
    yield* Files.writeIfChanged(themePath, updated).pipe(Target.step(name, "write", themePath))
    return "applies next launch"
  }),
}

export * as Yazi from "./Yazi.ts"
