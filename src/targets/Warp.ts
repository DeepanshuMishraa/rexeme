import { Effect } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"

const name = "warp"
const NAMES = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"] as const

export const render = (p: Palette): string => {
  const group = (offset: number) => NAMES.map((color, index) => `    ${color}: '${p.ansi[offset + index] ?? p.fg}'`).join("\n")
  return `# Generated by rexeme from Rex's "${p.name}" theme.
name: Rex
accent: '${p.accent}'
cursor: '${p.cursor}'
background: '${p.bg}'
foreground: '${p.fg}'
details: ${p.appearance === "dark" ? "darker" : "lighter"}
terminal_colors:
  normal:
${group(0)}
  bright:
${group(8)}
`
}

export const target: Target.Target = {
  name,
  detect: Effect.gen(function* () {
    const paths = yield* Paths.Service
    return yield* Target.exists(join(paths.home, ".warp"))
  }),
  apply: Effect.fn("Warp.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const path = join(paths.home, ".warp", "themes", "rex.yaml")
    yield* Files.writeIfChanged(path, render(palette)).pipe(Target.step(name, "write", path))
    return `updated the "Rex" theme; pick it once in Warp > Settings > Appearance`
  }),
}

export * as Warp from "./Warp.ts"
