import { Effect } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"
import { Text } from "../Text.ts"

const name = "btop"

export const render = (p: Palette): string => {
  const values: ReadonlyArray<readonly [string, string]> = [
    ["main_bg", p.bg], ["main_fg", p.fg], ["title", p.fg], ["hi_fg", p.accent],
    ["selected_bg", p.surface1], ["selected_fg", p.fg], ["inactive_fg", p.muted],
    ["graph_text", p.subtext], ["meter_bg", p.surface0], ["proc_misc", p.cyan],
    ["cpu_box", p.borderStrong], ["mem_box", p.borderStrong], ["net_box", p.borderStrong],
    ["proc_box", p.borderStrong], ["div_line", p.border],
    ["temp_start", p.green], ["temp_mid", p.yellow], ["temp_end", p.red],
    ["cpu_start", p.cyan], ["cpu_mid", p.blue], ["cpu_end", p.magenta],
    ["free_start", p.magenta], ["free_mid", p.magenta], ["free_end", p.blue],
    ["cached_start", p.blue], ["cached_mid", p.blue], ["cached_end", p.cyan],
    ["available_start", p.orange], ["available_mid", p.orange], ["available_end", p.yellow],
    ["used_start", p.green], ["used_mid", p.green], ["used_end", p.cyan],
    ["download_start", p.orange], ["download_mid", p.orange], ["download_end", p.red],
    ["upload_start", p.green], ["upload_mid", p.green], ["upload_end", p.cyan],
    ["process_start", p.blue], ["process_mid", p.cyan], ["process_end", p.accent],
  ]
  return [`# Generated by rexeme from Rex's "${p.name}" theme.`, ...values.map(([key, value]) => `theme[${key}]="${value}"`)].join("\n") + "\n"
}

export const target: Target.Target = {
  name,
  detect: Effect.gen(function* () {
    const paths = yield* Paths.Service
    return yield* Target.exists(join(paths.config, "btop", "btop.conf"))
  }),
  apply: Effect.fn("Btop.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const themePath = join(paths.config, "btop", "themes", "rex.theme")
    const configPath = join(paths.config, "btop", "btop.conf")
    yield* Files.writeIfChanged(themePath, render(palette)).pipe(Target.step(name, "write", themePath))
    const config = yield* Files.read(configPath).pipe(Target.step(name, "read", configPath))
    yield* Files.writeIfChanged(configPath, Text.setKeyValue(config, "color_theme", JSON.stringify(themePath))).pipe(
      Target.step(name, "write", configPath),
    )
    // SIGUSR2 makes btop reload btop.conf and its theme.
    return (yield* Target.reload("btop", "USR2")) ? "reloaded running btop" : "applies next launch"
  }),
}

export * as Btop from "./Btop.ts"
