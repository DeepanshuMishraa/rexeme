export const target: Target.Target = {
  name,
  detect: Target.onPath("eza"),
  apply: Effect.fn("Eza.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const dir = process.env["EZA_CONFIG_DIR"] ?? join(paths.config, "eza")
    const path = join(dir, "theme.yml")
    yield* Files.writeIfChanged(path, render(palette)).pipe(Target.step(name, "write", path))
    return "every new eza run uses it"
  }),
}

