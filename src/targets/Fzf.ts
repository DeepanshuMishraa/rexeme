import { Effect } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"

const name = "fzf"

export const render = (p: Palette): string => {
  const colors = [
    "bg:-1", `bg+:${p.surface1}`, `fg:${p.fg}`, `fg+:${p.fg}`, `hl:${p.accent}`, `hl+:${p.accent}`,
    `info:${p.muted}`, `prompt:${p.accent}`, `pointer:${p.accent}`, `marker:${p.green}`, `spinner:${p.accent}`,
    `header:${p.blue}`, `border:${p.border}`, `label:${p.subtext}`, `query:${p.fg}`, `gutter:-1`,
    `selected-bg:${p.surface0}`, `scrollbar:${p.borderStrong}`, `separator:${p.border}`,
  ]
  return `# Generated by rexeme from Rex's "${p.name}" theme.\n--color=${colors.join(",")}\n`
}

export const target: Target.Target = {
  name,
  detect: Target.onPath("fzf"),
  apply: Effect.fn("Fzf.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const path = join(paths.config, "fzf", "rex.fzfrc")
    yield* Files.writeIfChanged(path, render(palette)).pipe(Target.step(name, "write", path))
    return process.env["FZF_DEFAULT_OPTS_FILE"] === path
      ? "every new fzf uses it"
      : `export FZF_DEFAULT_OPTS_FILE=${path} in your shell to use it`
  }),
}

export * as Fzf from "./Fzf.ts"
