import { Effect, Option } from "effect"
import { join } from "node:path"
import { Files } from "../Files.ts"
import type { Palette } from "../Palette.ts"
import { Paths } from "../Paths.ts"
import { Target } from "../Target.ts"
import { Text } from "../Text.ts"

const name = "ghostty"

export const render = (p: Palette): string =>
  [
    `# Generated by rexeme from Rex's "${p.name}" theme.`,
    `background = ${p.bg}`,
    `foreground = ${p.fg}`,
    `cursor-color = ${p.cursor}`,
    `cursor-text = ${p.cursorText}`,
    `selection-background = ${p.selection}`,
    `selection-foreground = ${p.selectionFg}`,
    ...p.ansi.map((color, index) => `palette = ${index}=${color}`),
  ].join("\n") + "\n"

// Ghostty reads the XDG config first; the macOS one is a fallback.
const configPath = Effect.fn("Ghostty.configPath")(function* () {
  const paths = yield* Paths.Service
  const xdg = join(paths.config, "ghostty", "config")
  return (yield* Target.exists(xdg)) ? xdg : join(paths.appSupport, "com.mitchellh.ghostty", "config")
})

export const target: Target.Target = {
  name,
  detect: Effect.gen(function* () {
    const paths = yield* Paths.Service
    return (yield* Target.exists(join(paths.config, "ghostty"))) || (yield* Target.exists(join(paths.appSupport, "com.mitchellh.ghostty")))
  }),
  apply: Effect.fn("Ghostty.apply")(function* (palette) {
    const paths = yield* Paths.Service
    const themePath = join(paths.config, "ghostty", "themes", "rex")
    yield* Files.writeIfChanged(themePath, render(palette)).pipe(Target.step(name, "write", themePath))
    const path = yield* configPath()
    const config = Option.getOrElse(yield* Files.readOptional(path).pipe(Target.step(name, "read", path)), () => "")
    yield* Files.writeIfChanged(path, Text.setKeyValue(config, "theme", "rex")).pipe(Target.step(name, "write", path))
    // Colors set directly in the config win over the theme.
    const overridden = ["background", "foreground", "palette"].filter((key) => new RegExp(`^\\s*${key}\\s*=`, "m").test(config))
    // SIGUSR2 makes Ghostty reload its configuration.
    const reloaded = yield* Target.reload("ghostty", "USR2")
    const note = reloaded ? "reloaded running Ghostty" : "applies next launch"
    return overridden.length > 0 ? `${note}; ${overridden.join(", ")} set in ${path} still override it` : note
  }),
}

export * as Ghostty from "./Ghostty.ts"
