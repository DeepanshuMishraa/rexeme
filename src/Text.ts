import { Effect, Schema } from "effect"

/** Pure, format-preserving edits for config files rexeme doesn't own. */

const escapeRegExp = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")

/** Sets `key = value` in a `key = value` / `key=value` file such as btop.conf or htoprc. */
export const setKeyValue = (content: string, key: string, value: string, separator = " = ") => {
  const pattern = new RegExp(`^(\\s*${escapeRegExp(key)}\\s*=\\s*).*$`, "m")
  if (pattern.test(content)) return content.replace(pattern, (_, prefix: string) => `${prefix}${value}`)
  return `${content.replace(/\n*$/, "")}${content === "" ? "" : "\n"}${key}${separator}${value}\n`
}

/** Sets `key = value` inside TOML `[section]`, adding the section when absent. */
export const setTomlValue = (content: string, section: string, key: string, value: string) => {
  const header = new RegExp(`^\\s*\\[${escapeRegExp(section)}\\]\\s*$`, "m").exec(content)
  if (!header) return `${content.replace(/\n*$/, "")}\n\n[${section}]\n${key} = ${value}\n`
  const bodyStart = header.index + header[0].length
  const nextHeader = /^\s*\[[^\]]+\]\s*$/m.exec(content.slice(bodyStart))
  const bodyEnd = nextHeader ? bodyStart + nextHeader.index : content.length
  const body = content.slice(bodyStart, bodyEnd)
  const line = new RegExp(`^(\\s*${escapeRegExp(key)}\\s*=\\s*).*$`, "m")
  const updated = line.test(body)
    ? body.replace(line, (_, prefix: string) => `${prefix}${value}`)
    : `\n${key} = ${value}${body.startsWith("\n") ? "" : "\n"}${body}`
  return content.slice(0, bodyStart) + updated + content.slice(bodyEnd)
}

/**
 * Sets a top-level TOML `key = value`, which must come before the first
 * `[section]`. Replaces the key there, or inserts it above the first section.
 */
export const setTomlTopLevel = (content: string, key: string, value: string) => {
  const firstSection = /^\s*\[[^\]]+\]\s*$/m.exec(content)
  const headEnd = firstSection ? firstSection.index : content.length
  const head = content.slice(0, headEnd)
  const line = new RegExp(`^(\\s*${escapeRegExp(key)}\\s*=\\s*).*$`, "m")
  if (line.test(head)) return head.replace(line, (_, prefix: string) => `${prefix}${value}`) + content.slice(headEnd)
  if (!firstSection) return setKeyValue(content, key, value)
  return `${head}${key} = ${value}\n${content.slice(headEnd)}`
}

/**
 * Replaces the first line matching `pattern` with `line`, or appends `line`.
 * For formats without `=`, such as KDL (`theme "rex"`) or tmux (`source-file x`).
 */
export const setLine = (content: string, pattern: RegExp, line: string) => {
  const anchored = new RegExp(pattern.source, pattern.flags.includes("m") ? pattern.flags : `${pattern.flags}m`)
  if (anchored.test(content)) return content.replace(anchored, line)
  return `${content.replace(/\n*$/, "")}${content === "" ? "" : "\n"}${line}\n`
}

export class ManagedBlockConflict extends Schema.TaggedError<ManagedBlockConflict>()("Text.ManagedBlockConflict", {
  key: Schema.String,
}) {}

export interface Markers {
  readonly begin: string
  readonly end: string
}

/**
 * Replaces the YAML block between `markers`, appending it when absent. Blocks
 * between any of `replaces` (generated by an earlier tool) are removed too.
 * Fails when the rest of the file defines the same top-level `key`, because
 * YAML can't hold two and merging hand-written settings isn't safe.
 */
export const replaceYamlBlock = Effect.fn("Text.replaceYamlBlock")(function* (
  content: string,
  block: string,
  key: string,
  markers: Markers,
  replaces: ReadonlyArray<Markers> = [],
) {
  let outside = content
  for (const old of replaces) outside = removeBlock(outside, old)
  const current = findBlock(outside, markers)
  const rest = current ? outside.slice(0, current.start) + outside.slice(current.end) : outside
  if (new RegExp(`^${escapeRegExp(key)}\\s*:`, "m").test(rest)) return yield* new ManagedBlockConflict({ key })
  if (current) return outside.slice(0, current.start) + block + outside.slice(current.end).replace(/^\n/, "")
  return rest.trim() === "" ? block : `${rest.replace(/\n*$/, "")}\n\n${block}`
})

const findBlock = (content: string, { begin, end }: Markers) => {
  const start = content.indexOf(begin)
  const finish = content.indexOf(end, start)
  return start === -1 || finish === -1 ? undefined : { start, end: finish + end.length + (content[finish + end.length] === "\n" ? 1 : 0) }
}

const removeBlock = (content: string, markers: Markers) => {
  const found = findBlock(content, markers)
  return found ? content.slice(0, found.start) + content.slice(found.end).replace(/^\n/, "") : content
}

